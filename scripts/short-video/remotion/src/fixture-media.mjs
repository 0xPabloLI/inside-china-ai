/**
 * Generated-at-test-time media for the scene-gate fixture (#1093).
 *
 * Why this module exists: `contrast-media-render` and `scene-gate-render` bind
 * a picture in their scenes, and until #1093 that picture was
 * `assets/pexels-ai-chip.jpg` — a scraped Pexels photo kept out of the repo by
 * `.gitignore`'s `pexels-*` rule. A clean checkout therefore rendered a 404
 * where the photo should be, so neither suite could run in CI.
 *
 * The path is a CONSTANT shared by the fixture (which binds it) and
 * `__tests__/fixture-media.mjs` (which generates the file). Two files naming
 * the same string by hand silently drift apart, and the failure mode is the
 * one this ticket fixes — a 404 that only appears on a machine without the
 * asset.
 *
 * Why `assets/_fixture/` and not `public/fixture/`: `MediaBackground` resolves
 * every scene path through `staticFile()` after forcing an `assets/` prefix
 * (components/MediaBackground.tsx), so only `assets/...` is addressable
 * without changing render code — which this ticket does not.
 *
 * `scripts/short-video/assets/_fixture/` is gitignored: the file is a cache,
 * regenerated by ffmpeg whenever a suite starts, never committed.
 *
 * Plain `.mjs` on purpose: the fixture (bundled by Remotion) and the test
 * helper (run by Node/vitest) have to read the same value, and only a module
 * both loaders understand can be the single source.
 */
