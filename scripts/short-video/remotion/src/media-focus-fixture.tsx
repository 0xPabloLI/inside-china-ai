/**
 * MediaBackground focus-position fixture (#952).
 *
 * Dedicated entry point with its own registerRoot — Root.tsx is never touched.
 * Driven by __tests__/media-focus-render.test.mjs via `remotion still` (same
 * driver pattern as media-zoom-fixture.tsx).
 *
 * What it isolates: `cropFocus` / `focus` are DECLARED fields whose only
 * runtime effect is the `objectPosition` style. That effect is invisible to
 * every non-pixel gate — `checkMediaBandFill` only notices a letterbox, and a
 * frame sampled from the wrong part of the source still passes every safe-zone
 * check. `cropFocus` was never verified because until 2026-10-25 the video
 * branch silently rendered `contain`, where object-position has no effect at
 * all.
 *
 * The fixture assets are colour-coded sources generated by the test driver
 * into the gitignored `assets/_staged/` namespace (public/assets is a symlink
 * to assets/) and deleted afterwards:
 *
 *   media-focus-horizontal.png / .mp4 — 1920x1080, bands red | lime | blue
 *     left→right. In a 1080x1920 frame the visible window is narrower than a
 *     band, so cropFocus.x selects which band the frame centre samples.
 *
 *   media-focus-vertical.png / .mp4 — 540x1920, the same bands top→bottom.
 *     Taller than the frame, so the deprecated `focus` enum selects the band —
 *     and in the evidence card (820x618, a landscape box) it is also the only
 *     axis cover crops, which is what makes `focus` observable inside
 *     MediaCard.
 */
import React from "react";
import { AbsoluteFill, Composition, registerRoot } from "remotion";
import { MediaBackground } from "./components/MediaBackground";
import { MediaCard } from "./components/MediaCard";
import type { MediaField } from "./types";

const SOURCE_FILES = {
  horizontal: { image: "media-focus-horizontal.png", video: "media-focus-horizontal.mp4" },
  vertical: { image: "media-focus-vertical.png", video: "media-focus-vertical.mp4" },
} as const;

type FixtureProps = {
  /** Which fixture asset to render: a still or a real clip. */
  asset?: "image" | "video";
  /** Colour-band orientation of the generated source. */
  source?: "horizontal" | "vertical";
  /**
   * `background` renders MediaBackground directly (full-frame scenes);
   * `card` renders it through MediaCard, the evidence-card wrapper that must
   * pass media through unchanged.
   */
  wrap?: "background" | "card";
  /** `cropFocus.x` in [0,1]. Setting EITHER axis creates cropFocus; the other
   *  axis defaults to 0.5. Leaving both null leaves cropFocus absent. */
  cropFocusX?: number | null;
  /** `cropFocus.y` in [0,1]; same rule as cropFocusX. */
  cropFocusY?: number | null;
  /** Deprecated focus enum; only observable when cropFocus is absent. */
  focus?: "top" | "center" | "bottom" | null;
};

const buildMedia = ({
  asset = "image",
  source = "horizontal",
  cropFocusX = null,
  cropFocusY = null,
  focus = null,
}: FixtureProps): MediaField => {
  const media: MediaField = {
    type: asset,
    path: `assets/_staged/${SOURCE_FILES[source][asset]}`,
    animation: "none", // static frame: the pixel diff must isolate objectPosition
    volume: 0,
    overlay: 0, // no dim layer over the colours
  };
  if (typeof cropFocusX === "number" || typeof cropFocusY === "number") {
    media.cropFocus = { x: cropFocusX ?? 0.5, y: cropFocusY ?? 0.5 };
  }
  if (focus) media.focus = focus;
  return media;
};

const FixtureScene: React.FC<FixtureProps> = ({ wrap = "background", ...rest }) => {
  const media = buildMedia(rest);
  return (
    <AbsoluteFill style={{ background: "#000" }}>
      {wrap === "card" ? (
        <MediaCard media={media} duration={4} />
      ) : (
        <MediaBackground media={media} duration={4} />
      )}
    </AbsoluteFill>
  );
};

export const MediaFocusFixtureRoot: React.FC = () => (
  <Composition
    id="MediaFocusFixture"
    component={FixtureScene as unknown as React.FC<Record<string, unknown>>}
    durationInFrames={120}
    fps={30}
    width={1080}
    height={1920}
    defaultProps={{
      asset: "image",
      source: "horizontal",
      wrap: "background",
      cropFocusX: null,
      cropFocusY: null,
      focus: null,
    }}
  />
);

registerRoot(MediaFocusFixtureRoot);
