#!/usr/bin/env node
/**
 * Compilation Script — Plan B: Reconstruct Narrative
 *
 * Merges multiple scene-data files into a single compilation scene-data.
 * Removes per-episode hook/CTA scenes, keeps Part 1's hook + all middle content + last part's CTA.
 * Outputs a new scene-data .mjs file ready for `main.mjs --scene`.
 *
 * Usage:
 *   node scripts/short-video/compile-series-reconstruct.mjs --scenes pt1.mjs pt2.mjs pt3.mjs [--output compilation.mjs]
 *
 * Output:
 *   scripts/short-video/scene-data-compilation.mjs (default)
 */

import { writeFileSync } from "fs";
import { join, dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// ─── CLI args ───

const args = process.argv.slice(2);
function getScenes() {
  const i = args.indexOf("--scenes");
  if (i < 0 || i + 1 >= args.length) return [];
  const result = [];
  for (let j = i + 1; j < args.length && !args[j].startsWith("--"); j++) {
    result.push(args[j]);
  }
  return result;
}
function getArg(name) {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : null;
}

// ─── Pure functions (exported for testing) ───

/**
 * Filter out hook and CTA scenes from a scene array.
 * Hook = first scene OR scene with name "hook".
 * CTA = last scene OR scene with name "cta".
 *
 * @param {Array} scenes - scene array
 * @returns {Array} middle scenes only
 */
export function filterHookAndCta(scenes) {
  if (!scenes || scenes.length <= 2) return [];
  return scenes.slice(1, -1);
}

/**
 * Merge multiple scene arrays into a compilation scene array.
 * Takes: first hook + all middle content + last CTA.
 * Renumbers scene ids sequentially.
 *
 * @param {Array<Array>} sceneArrays - array of scene arrays
 * @returns {Array} merged and renumbered scenes
 */
export function mergeScenes(sceneArrays) {
  if (!sceneArrays || sceneArrays.length === 0) return [];
  if (sceneArrays.length === 1) {
    return renumberScenes([...sceneArrays[0]]);
  }

  const hookScene = sceneArrays[0][0]; // Part 1's hook
  const ctaScene =
    sceneArrays[sceneArrays.length - 1][sceneArrays[sceneArrays.length - 1].length - 1]; // Last part's CTA

  // Collect all middle scenes
  const middleScenes = [];
  for (const scenes of sceneArrays) {
    middleScenes.push(...filterHookAndCta(scenes));
  }

  const merged = [hookScene, ...middleScenes, ctaScene];
  return renumberScenes(merged);
}

/**
 * Renumber scene ids sequentially starting from 1.
 */
function renumberScenes(scenes) {
  return scenes.map((s, i) => ({ ...s, id: i + 1 }));
}

// ─── Main ───

async function main() {
  const sceneFiles = getScenes();
  const outputPath = getArg("output") || join(__dirname, "scene-data-compilation.mjs");

  if (sceneFiles.length === 0) {
    console.error("❌ No scene files specified. Use --scenes <path1> <path2> ...");
    process.exit(1);
  }

  console.log("🎬 Compilation Script — Plan B (Reconstruct Narrative)");
  console.log("=".repeat(60));

  console.log(`📹 Input: ${sceneFiles.length} scene file(s)`);
  sceneFiles.forEach((f, i) => console.log(`  ${i + 1}. ${f}`));

  // Dynamic import all scene files
  console.log("\n📥 Loading scene files...");
  const sceneArrays = [];
  for (const file of sceneFiles) {
    try {
      const absPath = resolve(file);
      const mod = await import(absPath);
      if (!mod.scenes || !Array.isArray(mod.scenes) || mod.scenes.length === 0) {
        console.error(`❌ No scenes array found in ${file}`);
        process.exit(1);
      }
      sceneArrays.push(mod.scenes);
      console.log(`  ✅ ${file}: ${mod.scenes.length} scenes`);
    } catch (e) {
      console.error(`❌ Failed to import ${file}: ${e.message}`);
      process.exit(1);
    }
  }

  // Merge scenes
  console.log("\n🔧 Merging scenes...");
  const merged = mergeScenes(sceneArrays);

  const hookCount = sceneArrays.reduce((n, s) => n + 1, 0); // each has a hook
  const ctaCount = sceneArrays.reduce((n, s) => n + 1, 0); // each has a CTA
  const removedScenes = hookCount - 1 + ctaCount - 1; // keep first hook + last cta

  console.log(`  Original total: ${sceneArrays.reduce((n, s) => n + s.length, 0)} scenes`);
  console.log(`  Removed: ${removedScenes} (hook/CTA from middle episodes)`);
  console.log(`  Merged: ${merged.length} scenes`);

  // Generate output file
  const output = `/**
 * Compilation Scene Data — Auto-generated by compile-series-reconstruct.mjs
 * Merged from: ${sceneFiles.join(", ")}
 * DO NOT EDIT MANUALLY — regenerate with compile-series-reconstruct.mjs
 */

export const scenes = ${JSON.stringify(merged, null, 2)};
`;

  writeFileSync(outputPath, output, "utf8");

  console.log("\n" + "=".repeat(60));
  console.log("✅ Compilation scene-data generated!");
  console.log(`   📁 Output: ${outputPath}`);
  console.log(`   🎬 Total scenes: ${merged.length}`);
  console.log(
    "   📋 Next step: place the output as content/<dir>/scene-data.mjs (add meta.mjs + scenes.mjs in the same dir), then run node scripts/short-video/main.mjs --content <dir>",
  );
  console.log("=".repeat(60));
}

// Run main only when executed directly (not when imported by tests)
if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(`❌ ${e.message}`);
    process.exit(1);
  });
}
