/**
 * Tests for the preinstalled site-packages fast path (#1520).
 *
 * The cold-run install is 211–309s of every Kaggle kernel; the dataset carries
 * the same tree already installed. This file pins the two things a green unit
 * suite would otherwise miss:
 *
 *  - the mount check is executed for real against synthetic mounts (missing /
 *    drifted / unpacked layouts), not only grepped for;
 *  - the kernel activates the tree *before* `import torch`, skips the install
 *    only when the probe passed, and still exits build mode before CosyVoice.
 */
import { describe, expect, it } from "vitest";
import { execFileSync } from "child_process";
import { createHash } from "crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";

const KAGGLE_DIR = join(import.meta.dirname, "..", "kaggle");
const KERNEL_SRC = readFileSync(join(KAGGLE_DIR, "cosyvoice3_cuda_kernel.py"), "utf-8");
const ADAPTER_SRC = readFileSync(
  join(import.meta.dirname, "..", "lib", "tts", "cosyvoice3-kaggle-cuda.mjs"),
  "utf-8",
);

const PROBLEMS_SRC = KERNEL_SRC.slice(
  KERNEL_SRC.indexOf("def _site_packages_problems"),
  KERNEL_SRC.indexOf("def _activate_site_packages"),
);

/** Run the kernel's real manifest check against a synthetic mount. */
function problems({
  expected,
  mounted,
  tarBytes = 32,
  unpacked = false,
  flattened = false,
  omitTar = false,
  zst = false,
}) {
  const dir = mkdtempSync(join(tmpdir(), "site-packages-"));
  try {
    writeFileSync(join(dir, "manifest.json"), JSON.stringify(mounted));
    if (unpacked) {
      mkdirSync(join(dir, "site-packages"));
    } else if (flattened) {
      mkdirSync(join(dir, "torch"));
    } else if (!omitTar) {
      writeFileSync(
        join(dir, zst ? "site-packages.tar.zst" : "site-packages.tar"),
        Buffer.alloc(tarBytes),
      );
    }
    const script = [
      "import json, os, sys",
      PROBLEMS_SRC,
      "mount, expected = sys.argv[1], json.loads(sys.argv[2])",
      "print(json.dumps(_site_packages_problems(mount, expected)))",
    ].join("\n");
    const out = execFileSync("python3", ["-c", script, dir, JSON.stringify(expected)], {
      encoding: "utf-8",
    });
    return JSON.parse(out);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const MATCHING_MANIFEST = {
  dists: { torch: "2.6.0+cu124", "huggingface-hub": "0.36.2", diffusers: "0.32.2" },
  tarBytes: 32,
};

describe("site-packages mount check (#1520)", () => {
  it("accepts a matching tar mount", () => {
    expect(problems({ expected: MATCHING_MANIFEST, mounted: MATCHING_MANIFEST })).toEqual([]);
  });

  it("accepts the zstd envelope the dataset publishes", () => {
    expect(
      problems({ expected: MATCHING_MANIFEST, mounted: MATCHING_MANIFEST, zst: true }),
    ).toEqual([]);
  });

  it("accepts the unpacked layout Kaggle may produce", () => {
    expect(
      problems({ expected: MATCHING_MANIFEST, mounted: MATCHING_MANIFEST, unpacked: true }),
    ).toEqual([]);
  });

  it("accepts a tar Kaggle expanded flat into the mount root", () => {
    expect(
      problems({ expected: MATCHING_MANIFEST, mounted: MATCHING_MANIFEST, flattened: true }),
    ).toEqual([]);
  });

  it("rejects a missing distribution", () => {
    const mounted = { ...MATCHING_MANIFEST, dists: { ...MATCHING_MANIFEST.dists } };
    delete mounted.dists.diffusers;
    const found = problems({ expected: MATCHING_MANIFEST, mounted });
    expect(found.join(" ")).toContain("missing distributions: ['diffusers']");
  });

  it("rejects a changed version", () => {
    const mounted = {
      ...MATCHING_MANIFEST,
      dists: { ...MATCHING_MANIFEST.dists, torch: "2.5.0+cu121" },
    };
    expect(problems({ expected: MATCHING_MANIFEST, mounted }).join(" ")).toContain(
      "different versions",
    );
  });

  it("rejects a tar whose bytes changed without the manifest noticing", () => {
    expect(
      problems({ expected: MATCHING_MANIFEST, mounted: MATCHING_MANIFEST, tarBytes: 31 }).join(" "),
    ).toContain("the manifest records 32");
  });

  it("rejects a mount with no archive or unpacked tree", () => {
    const found = problems({
      expected: MATCHING_MANIFEST,
      mounted: MATCHING_MANIFEST,
      omitTar: true,
    });
    expect(found.join(" ")).toContain("neither site-packages/ nor site-packages.tar(.zst)");
  });

  it("rejects an empty committed manifest instead of trusting a mount", () => {
    const found = problems({ expected: { dists: {} }, mounted: MATCHING_MANIFEST });
    expect(found.join(" ")).toContain("lists no distributions");
  });
});

describe("kernel activation order (#1520)", () => {
  it("activates before the first torch import", () => {
    const activateAt = KERNEL_SRC.indexOf("_activate_site_packages()");
    const torchAt = KERNEL_SRC.indexOf("try:\n    import torch");
    expect(activateAt).toBeGreaterThan(-1);
    expect(torchAt).toBeGreaterThan(-1);
    expect(activateAt).toBeLessThan(torchAt);
  });

  it("only treats the fast path as active after the probe passed", () => {
    // SITE_PACKAGES_ACTIVE is set from the probe result, not from the mount's
    // existence: a mount that cannot import torch on its own must fall back.
    expect(KERNEL_SRC).toContain("SITE_PACKAGES_ACTIVE = _SITE_PACKAGES_TARGET is not None");
    expect(KERNEL_SRC).toContain(
      'subprocess.run(\n            [sys.executable, "-S", "-c", probe]',
    );
  });

  it("makes every pip install a no-op on the fast path", () => {
    // A green fast path must not even print the install section: the log is
    // the acceptance evidence, and a lingering header reads as "it installed".
    expect(KERNEL_SRC).toContain(
      'if not SITE_PACKAGES_ACTIVE:\n    log("\\n=== Installing deps ===")',
    );
    const fnAt = KERNEL_SRC.indexOf("def _pip_install(args, online_extra=None):");
    const installAt = KERNEL_SRC.indexOf(
      'cmd = [\n            exe, "-m", "pip", "install", "-q",\n            "--no-index"',
    );
    expect(fnAt).toBeGreaterThan(-1);
    expect(installAt).toBeGreaterThan(fnAt);
    expect(KERNEL_SRC.slice(fnAt, installAt)).toContain("if SITE_PACKAGES_ACTIVE:");
    expect(KERNEL_SRC.slice(fnAt, installAt)).toContain("return");
  });

  it("carries the mounted tree across the inference-child exec boundary", () => {
    // The child is a fresh interpreter; without PYTHONPATH it cannot see the
    // packages the parent put on sys.path, and the first `hyperpyyaml` import
    // fails (2026-11-23 P100 run).
    expect(KERNEL_SRC).toContain('_child_env["PYTHONPATH"] = (');
    expect(KERNEL_SRC).toContain("env=_child_env");
  });

  it("unpacks the zstd envelope in-process when Kaggle kept it compressed", () => {
    expect(KERNEL_SRC).toContain("zstandard.ZstdDecompressor().stream_reader");
    expect(KERNEL_SRC).toContain('mode="r|"');
    expect(KERNEL_SRC).toContain('archive.extract(member, target, filter="data")');
  });

  it("installs through the build venv and exits before the CosyVoice clone", () => {
    // `pip --target` cannot downgrade an already-present transitive pin, so
    // build mode goes through a venv whose pip sees the installed set.
    expect(KERNEL_SRC).toContain("exe = BUILD_SITE_PACKAGES_PYTHON or sys.executable");
    expect(KERNEL_SRC).not.toContain('cmd += ["--target", BUILD_SITE_PACKAGES_TARGET]');
    expect(KERNEL_SRC).toContain("SITE_PACKAGES_BUILD_OK");
    const buildExitAt = KERNEL_SRC.indexOf("SITE_PACKAGES_BUILD_OK");
    const sourceAt = KERNEL_SRC.indexOf("=== Setting up CosyVoice source ===");
    expect(buildExitAt).toBeGreaterThan(-1);
    expect(sourceAt).toBeGreaterThan(-1);
    expect(buildExitAt).toBeLessThan(sourceAt);
  });

  it("does not assert the CUDA provider during a CPU build", () => {
    expect(KERNEL_SRC).toContain(
      'if "CUDAExecutionProvider" not in providers and not BUILD_SITE_PACKAGES_TARGET:',
    );
  });
});

describe("committed site-packages manifest (#1520)", () => {
  const manifest = JSON.parse(
    readFileSync(join(KAGGLE_DIR, "site-packages-manifest.json"), "utf-8"),
  );
  const wheelhouse = readFileSync(join(KAGGLE_DIR, "wheelhouse-manifest.json"));

  it("was built from the wheelhouse this repo currently freezes", () => {
    // A rebuilt wheelhouse changes the installed set; the dataset then has to
    // be rebuilt too. Failing here is the cheap reminder, not a runtime fallback.
    expect(manifest.wheelhouseManifestSha256).toBe(
      createHash("sha256").update(wheelhouse).digest("hex"),
    );
  });

  it("records the archive size and the pinned runtime", () => {
    expect(manifest.tarBytes).toBeGreaterThan(1_000_000_000);
    expect(manifest.tarSha256).toMatch(/^[0-9a-f]{64}$/);
    expect(manifest.dists.torch).toBe("2.6.0+cu124");
    expect(manifest.dists["huggingface-hub"]).toBe("0.36.2");
    expect(manifest.dists.diffusers).toBe("0.32.2");
    expect(manifest.dists["onnxruntime-gpu"]).toBe("1.20.0");
  });
});

describe("adapter wiring (#1520)", () => {
  it("reads the committed manifest and injects it", () => {
    expect(ADAPTER_SRC).toContain(
      'const KAGGLE_SITE_PACKAGES_MANIFEST = join(ROOT_DIR, "kaggle", "site-packages-manifest.json")',
    );
    expect(ADAPTER_SRC).toContain(
      '.replaceAll("__EXPECTED_SITE_PACKAGES__", sitePackagesExpected)',
    );
  });

  it("attaches the dataset only after the repo records the set", () => {
    // A dataset source that does not exist makes `kernels push` fail outright,
    // so `{}` (no committed manifest) must also mean "not attached".
    expect(ADAPTER_SRC).toContain(
      'sitePackagesExpected === "{}" ? [] : ["xPabloLI/cosyvoice3-site-packages"]',
    );
    expect(ADAPTER_SRC).toContain("...sitePackagesSources,");
  });
});
