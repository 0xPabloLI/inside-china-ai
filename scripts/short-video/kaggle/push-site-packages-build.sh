#!/usr/bin/env bash
# push-site-packages-build.sh — deliver the #1520 site-packages build to Kaggle.
#
# The build has to run on Kaggle: the wheelhouse is already mounted there, the
# 3.7GB install and the tar happen on Kaggle's disk/network, and the CLI inside
# a kernel is authenticated so the dataset push needs no local credentials.
#
# Usage:
#   scripts/short-video/kaggle/push-site-packages-build.sh [-t SECONDS]
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD="$HERE/build-site-packages-dataset.sh"
KERNEL="$HERE/cosyvoice3_cuda_kernel.py"
MANIFEST="$HERE/wheelhouse-manifest.json"
KERNEL_ID="xPabloLI/1520-build-site-packages"

for f in "$BUILD" "$KERNEL" "$MANIFEST"; do
  [ -f "$f" ] || { echo "FAIL: missing $f" >&2; exit 1; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

HERE_FOR_PY="$HERE" WORK_FOR_PY="$WORK" python3 - <<'PY'
import base64, json, os, pathlib, time

here = pathlib.Path(os.environ["HERE_FOR_PY"])
work = pathlib.Path(os.environ["WORK_FOR_PY"])

build = here.joinpath("build-site-packages-dataset.sh").read_text()
manifest = here.joinpath("wheelhouse-manifest.json").read_text()
kernel = here.joinpath("cosyvoice3_cuda_kernel.py").read_text()

# The build kernel has no manifest of its own; the fast path is disabled by
# `{}` and the script exits in build mode before it would be consulted.
kernel = (
    kernel.replace("__MANIFEST_JSON__", "[]")
    .replace("__REQUEST_ID__", f"site-packages-build-{int(time.time())}")
    .replace("__LIVE_MODE__", "0")
    .replace("__CONTROL_URL__", "")
    .replace("__LIVE_IDLE_TIMEOUT_SEC__", "0")
    .replace("__LIVE_CONTROL_POLL_SEC__", "10")
    .replace("__KERNEL_WALL_CLOCK_BUDGET_SEC__", "10800")
    .replace("__KERNEL_HEARTBEAT_SEC__", "60")
    .replace("__EXPECTED_WHEELHOUSE__", manifest.strip())
    .replace("__EXPECTED_SITE_PACKAGES__", "{}")
)


def blob(text: str) -> str:
    return base64.b64encode(text.encode()).decode()


CARRIER = '''"""Build + publish xpabloli/cosyvoice3-site-packages (#1520).

GENERATED by scripts/short-video/kaggle/push-site-packages-build.sh — do not edit.
The repo's build script, kernel template and wheelhouse manifest are embedded
below and stay the single source.
"""
import base64, os, subprocess, sys

# Same CLI version as the repo's local tooling; the kernel env holds the
# credentials, so the dataset push needs nothing from the laptop.
subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q", "--upgrade", "kaggle==2.2.4"],
    check=True,
)

FILES = {
    "/kaggle/working/build-site-packages-dataset.sh": "@@BUILD@@",
    "/kaggle/working/cosyvoice3_cuda_kernel.py": "@@KERNEL@@",
    "/kaggle/working/wheelhouse-manifest.json": "@@MANIFEST@@",
}
for path, payload in FILES.items():
    with open(path, "w") as f:
        f.write(base64.b64decode(payload).decode())
os.chmod("/kaggle/working/build-site-packages-dataset.sh", 0o755)

os.environ["TMPDIR"] = "/kaggle/working/tmp"
os.makedirs(os.environ["TMPDIR"], exist_ok=True)

r = subprocess.run(["bash", "/kaggle/working/build-site-packages-dataset.sh"])
print("\\nbuild-site-packages-dataset.sh exit:", r.returncode)
sys.exit(r.returncode)
'''.replace("@@BUILD@@", blob(build)).replace("@@KERNEL@@", blob(kernel)).replace("@@MANIFEST@@", blob(manifest))

work.joinpath("build.py").write_text(CARRIER)
work.joinpath("kernel-metadata.json").write_text(
    json.dumps(
        {
            "id": "xPabloLI/1520-build-site-packages",
            "title": "1520-build-site-packages",
            "code_file": "build.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": False,
            "enable_internet": True,
            "dataset_sources": ["xpabloli/cosyvoice3-wheels"],
            "competition_sources": [],
            "kernel_sources": [],
            "model_sources": [],
        },
        indent=2,
    )
    + "\n"
)
print(f"carrier written: {work}")
PY

echo "==> pushing $KERNEL_ID"
kaggle kernels push -p "$WORK" "$@"
echo "==> watch: kaggle kernels status $KERNEL_ID"
