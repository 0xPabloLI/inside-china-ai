#!/usr/bin/env bash
# build-site-packages-dataset.sh — publish the preinstalled TTS environment (#1520).
#
# Runs ON Kaggle, inside the carrier kernel pushed by push-site-packages-build.sh.
# The carrier embeds cosyvoice3_cuda_kernel.py (rendered from the repo template)
# and wheelhouse-manifest.json next to this file, so the install pins are the
# same ones a production run would use — no second copy to drift.
#
# The kernel script is run in build mode: it installs every dependency into a
# venv, records the exact distribution set, and exits before cloning CosyVoice
# or loading a model. This script then proves the tree can import torch on its
# own, packs it into one `.tar.zst` (a plain archive is expanded by Kaggle at
# upload, which turns 112 dists into tens of thousands of files), records the
# manifest git will keep, and publishes the dataset.
#
# Requires: the wheelhouse dataset mounted (offline install), kaggle CLI
# authenticated inside the kernel, ~20GB working disk.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV="${SITE_PACKAGES_VENV_DIR:-/kaggle/working/venv}"
OUT="${SITE_PACKAGES_DATASET_DIR:-/kaggle/working/site-packages-dataset}"
DATASET_ID="xpabloli/cosyvoice3-site-packages"

# A venv is intentional: pip must see what it has already installed so a later
# pin can replace a transitive dependency already pulled in by an earlier
# package. `pip --target` can silently keep the earlier version.
#
# Kaggle's `python3 -m venv` cannot bootstrap pip (`ensurepip` exits 1 on this
# image), so create the venv without it and copy the image's pip into the
# venv. `-m pip` then installs into the venv because sys.prefix is the venv,
# and it sees only what the venv holds — exactly the resolver behaviour needed.
if [ ! -x "$VENV/bin/python" ]; then
  echo "==> creating build venv at $VENV"
  python3 -m venv --without-pip --copies "$VENV"
fi
PYVER="$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
TARGET="$VENV/lib/python$PYVER/site-packages"

if ! "$VENV/bin/python" -m pip --version >/dev/null 2>&1; then
  echo "==> bootstrapping pip into the venv from the image"
  mkdir -p "$TARGET"
  for root in "/usr/local/lib/python$PYVER/dist-packages" "/usr/local/lib/python$PYVER/site-packages"; do
    for d in "$root"/pip "$root"/pip-*.dist-info; do
      [ -e "$d" ] && cp -a "$d" "$TARGET/"
    done
  done
fi
"$VENV/bin/python" -m pip --version >/dev/null

export COSYVOICE3_SITE_PACKAGES_TARGET="$TARGET"
export COSYVOICE3_BUILD_PYTHON="$VENV/bin/python"
export PIP_NO_CACHE_DIR=1
export TMPDIR="${TMPDIR:-/kaggle/working/tmp}"
mkdir -p "$TARGET" "$OUT" "$TMPDIR"

echo "==> disk before build"
df -h /kaggle/working | tail -1

echo "==> installing the frozen wheelhouse into $TARGET"
python3 "$HERE/cosyvoice3_cuda_kernel.py"

test -s /kaggle/working/site-packages-dists.json || {
  echo "FAIL: build mode produced no site-packages-dists.json" >&2
  exit 1
}

echo "==> proving the tree is self-sufficient (python -S, no image site-packages)"
python3 -S - "$TARGET" <<'PY'
import sys

target = sys.argv[1]
sys.path.insert(0, target)
import torch, onnxruntime, diffusers, huggingface_hub, numba, librosa  # noqa: E402

for mod in (torch, onnxruntime, diffusers, huggingface_hub, numba, librosa):
    path = getattr(mod, "__file__", "")
    if not path.startswith(target):
        raise SystemExit(f"FAIL: {mod.__name__} imported outside the target: {path}")
print(
    "IMPORT_OK",
    f"torch={torch.__version__}",
    f"onnxruntime={onnxruntime.__version__}",
    f"diffusers={diffusers.__version__}",
    f"hub={huggingface_hub.__version__}",
    f"numba={numba.__version__}",
    f"librosa={librosa.__version__}",
)
PY

SIZE_BYTES=$(du -sb "$TARGET" | cut -f1)
echo "==> target is $SIZE_BYTES bytes; packing one tar.zst"
df -h /kaggle/working | tail -1
# `.tar.zst`, not `.tar`: Kaggle expands plain archives on upload, which for a
# flat site-packages tree means tens of thousands of files and a 45–60 min
# bundling step (and >50 top-level entries). A zstd envelope stays one file;
# the image ships the `zstandard` Python module (probed 2026-11-23), so the
# build needs no `zstd` binary.
ARCHIVE="$OUT/site-packages.tar.zst"
python3 - "$TARGET" "$ARCHIVE" <<'PY'
import sys, tarfile, zstandard

target, archive = sys.argv[1:]
with open(archive, "wb") as raw:
    cctx = zstandard.ZstdCompressor(level=3, threads=-1)
    with cctx.stream_writer(raw) as compressed:
        with tarfile.open(fileobj=compressed, mode="w|") as tar:
            tar.add(target, arcname="site-packages")
PY

# Free the venv before the upload: the archive is the artifact, and the
# carrier's working disk is the only place with room for both during packing.
rm -rf "$VENV"

TAR_BYTES=$(stat -c%s "$ARCHIVE")
TAR_SHA=$(sha256sum "$ARCHIVE" | cut -d' ' -f1)
WHEELS_SHA=$(sha256sum "$HERE/wheelhouse-manifest.json" | cut -d' ' -f1)

python3 - "$OUT" "$TAR_BYTES" "$TAR_SHA" "$WHEELS_SHA" "$SIZE_BYTES" <<'PY'
import json, os, sys, time

out, tar_bytes, tar_sha, wheels_sha, unpacked_bytes = sys.argv[1:]
with open("/kaggle/working/site-packages-dists.json") as f:
    built = json.load(f)
manifest = {
    **built,
    "archive": "site-packages.tar.zst",
    "archiveFormat": "tar.zst",
    "tarBytes": int(tar_bytes),
    "tarSha256": tar_sha,
    "unpackedBytes": int(unpacked_bytes),
    "wheelhouseManifestSha256": wheels_sha,
    "builtAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    "note": (
        "Written by build-site-packages-dataset.sh (#1520). The kernel compares "
        "the mounted manifest with site-packages-manifest.json in git before "
        "putting this tree on sys.path. Kaggle may unpack an archive on mount; "
        "a directory, a flat mount, and a tar.zst all count."
    ),
}
with open(os.path.join(out, "manifest.json"), "w") as f:
    json.dump(manifest, f, indent=2, sort_keys=True)
print("SITE_PACKAGES_MANIFEST_BEGIN")
print(json.dumps(manifest, indent=2, sort_keys=True))
print("SITE_PACKAGES_MANIFEST_END")
PY

cat > "$OUT/dataset-metadata.json" <<JSON
{
  "title": "cosyvoice3-site-packages",
  "id": "$DATASET_ID",
  "licenses": [{ "name": "other" }]
}
JSON

echo "==> publishing $DATASET_ID"
# Outside $OUT: the CLI uploads every file in the dataset directory, and a
# write-in-progress log both bloats the dataset and races the upload.
PUSH_LOG="/kaggle/working/site-packages-push.log"
kaggle datasets create -p "$OUT" --dir-mode skip >"$PUSH_LOG" 2>&1 || true
if grep -qi "already.*exists\|already in use" "$PUSH_LOG"; then
  echo "    dataset exists — publishing a new version"
  kaggle datasets version -p "$OUT" --dir-mode skip \
    -m "site-packages rebuild $(date -u +%Y-%m-%dT%H:%MZ)" >"$PUSH_LOG" 2>&1 || true
fi
cat "$PUSH_LOG"
if grep -qi "creation error" "$PUSH_LOG"; then
  echo "FAIL: the dataset push was rejected" >&2
  exit 1
fi
if ! grep -qiE "dataset( version)? is being created" "$PUSH_LOG"; then
  echo "FAIL: the push never reported a created dataset (the CLI exits 0 even when it fails)" >&2
  exit 1
fi
rm -f "$PUSH_LOG"

echo "✅ Done: $DATASET_ID published."
echo "   Copy the manifest above into scripts/short-video/kaggle/site-packages-manifest.json,"
echo "   then the production kernel will attach the dataset and use the fast path."
