/**
 * Generates docs/api.md from openapi.yaml (single source of truth for the
 * HTTP surface). Run via `npm run docs:api`; CI re-runs the generator and
 * fails if the committed output drifted from the spec.
 *
 * Usage: node scripts/generate-api-docs.mjs [--check]
 *   --check  exit 1 if docs/api.md is stale (no write)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { load as loadYaml } from "js-yaml";

const specPath = "openapi.yaml";
const outPath = "docs/api.md";
const check = process.argv.includes("--check");

const spec = loadYaml(readFileSync(specPath, "utf8"));

const lines = [];

lines.push(
  "<!-- AUTO-GENERATED by scripts/generate-api-docs.mjs from openapi.yaml — do not edit by hand. Run `npm run docs:api`. -->",
  "",
  "# API Reference",
  "",
  `${spec.info.description.trim()}`,
  "",
  `Version: ${spec.info.version}`,
  "",
);

for (const [path, item] of Object.entries(spec.paths)) {
  lines.push(`## \`${path}\``, "");
  for (const [method, op] of Object.entries(item)) {
    if (method === "parameters") continue;
    lines.push(`### \`${method.toUpperCase()} ${path}\``, "", `**${op.summary}**`, "");
    if (op.description) lines.push(op.description.trim(), "");
    if (op.security?.length) {
      const schemeName = Object.keys(op.security[0])[0];
      const scheme = spec.components.securitySchemes[schemeName];
      lines.push(`Auth: \`${scheme.name}\` header (${scheme.description ?? schemeName})`, "");
    } else {
      lines.push("Auth: none (public).", "");
    }
    const responses = Object.entries(op.responses ?? {});
    if (responses.length) {
      lines.push("| Status | Meaning |", "| --- | --- |");
      for (const [status, res] of responses) {
        lines.push(`| ${status} | ${(res.description ?? "").replace(/\|/g, "\\|")} |`);
      }
      lines.push("");
    }
  }
}

const output = lines.join("\n");

if (check) {
  const current = readFileSync(outPath, "utf8");
  if (current !== output) {
    console.error(`docs/api.md is stale — run \`npm run docs:api\` after changing openapi.yaml.`);
    process.exit(1);
  }
  console.log("docs/api.md is up to date.");
} else {
  writeFileSync(outPath, output);
  console.log(`Wrote ${outPath} (${spec.paths ? Object.keys(spec.paths).length : 0} paths).`);
}
